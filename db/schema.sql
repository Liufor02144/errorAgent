-- erroragent 表结构（MySQL 8）
-- 在目标库中执行：mysql -u <user> -p <database> < db/schema.sql

CREATE TABLE IF NOT EXISTS `ai_inspect_config` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `cfg_key` varchar(100) NOT NULL COMMENT '配置键',
  `cfg_value` varchar(2000) DEFAULT NULL COMMENT '当前值',
  `default_value` varchar(2000) DEFAULT NULL COMMENT '默认值',
  `value_type` varchar(20) NOT NULL DEFAULT 'STRING' COMMENT '类型：INT/LONG/BOOL/STRING/LIST',
  `group_name` varchar(50) NOT NULL DEFAULT 'DEFAULT' COMMENT '分组：COLLECT/JUDGE/TEMPLATE/EVENT/LLM/PUSH',
  `description` varchar(500) DEFAULT NULL COMMENT '说明',
  `operator` varchar(50) DEFAULT NULL COMMENT '最近修改人',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_cfg_key` (`cfg_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='巡检-动态配置';

CREATE TABLE IF NOT EXISTS `ai_inspect_fingerprint` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `fp_hash` char(32) NOT NULL COMMENT 'fp_key 的 MD5，唯一标识',
  `fp_key` varchar(1000) NOT NULL COMMENT '指纹原文',
  `app_id` varchar(100) NOT NULL COMMENT '服务名',
  `has_stack` tinyint(1) NOT NULL COMMENT '是否有堆栈：决定指纹构成方式',
  `exc_simple` varchar(100) DEFAULT NULL COMMENT '异常类简名(末段)',
  `logger_class` varchar(200) DEFAULT NULL COMMENT '缩写 logger(无堆栈时参与指纹)',
  `biz_frame` varchar(200) DEFAULT NULL COMMENT '首个业务栈帧，格式 File.java:line',
  `msg_tpl` varchar(500) DEFAULT NULL COMMENT '模板化后的 message 首行',
  `exc_cause` varchar(200) DEFAULT NULL COMMENT '异常真实原因',
  `template_id` bigint unsigned DEFAULT NULL COMMENT '所属异常模版ID。NULL 表示还没匹配上任何模版，待抽取',
  `first_seen_time` datetime NOT NULL COMMENT '历史首次出现时间',
  `last_seen_time` datetime NOT NULL COMMENT '最近一次出现时间',
  `total_count` bigint NOT NULL DEFAULT '0' COMMENT '累计出现次数',
  `status` varchar(20) NOT NULL DEFAULT 'ACTIVE' COMMENT '状态：ACTIVE/SUPPRESSED/ARCHIVED',
  `judge_state` varchar(20) DEFAULT NULL COMMENT '最近判定：NEW/SURGE/KNOWN',
  `category` varchar(20) DEFAULT NULL COMMENT 'AI分类：BIZ_EXPECTED/SUSPECTED_BUG/INFRA/NEEDS_INFO',
  `severity` varchar(4) DEFAULT NULL COMMENT '严重度：P0/P1/P2/P3',
  `handled` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否已人工标注：0-未处理，1-已处理',
  `pushed_time` datetime DEFAULT NULL COMMENT '最近推送时间，NULL 表示从未推送',
  `push_count` int NOT NULL DEFAULT '0' COMMENT '累计推送次数',
  `last_message_id` varchar(64) DEFAULT NULL COMMENT '最近一张卡片的飞书消息ID',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `deleted` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否删除：0-否，1-是',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_fp_hash` (`fp_hash`),
  KEY `idx_handled_state` (`handled`,`judge_state`,`last_seen_time`) COMMENT '列表页默认视图：未处理的新增/突增',
  KEY `idx_app_status` (`app_id`,`status`),
  KEY `idx_first_seen` (`first_seen_time`),
  KEY `idx_biz_frame` (`biz_frame`) COMMENT '跨服务同栈帧聚合视图用',
  KEY `idx_template` (`template_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='巡检-异常指纹库';

CREATE TABLE IF NOT EXISTS `ai_inspect_stat` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `fp_id` bigint unsigned NOT NULL COMMENT '指纹ID',
  `stat_hour` datetime NOT NULL COMMENT '统计时段起点（5 分钟桶；列名沿用旧的小时粒度命名）',
  `cnt` int NOT NULL DEFAULT '0' COMMENT '该时段出现次数',
  `batch_id` varchar(50) NOT NULL COMMENT '采集批次ID，重跑时按此清理保证幂等',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_fp_hour` (`fp_id`,`stat_hour`) COMMENT '采集窗口重叠时覆盖而非累加',
  KEY `idx_hour` (`stat_hour`),
  KEY `idx_batch` (`batch_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='巡检-指纹时序统计';

CREATE TABLE IF NOT EXISTS `ai_inspect_sample` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `fp_id` bigint unsigned NOT NULL COMMENT '指纹ID',
  `raw_message` text COMMENT '原始 message 全文(含完整堆栈)',
  `trace_id` varchar(100) DEFAULT NULL COMMENT '链路 traceId',
  `pod_name` varchar(200) DEFAULT NULL COMMENT '来源实例',
  `image_tag` varchar(100) DEFAULT NULL COMMENT '镜像 tag',
  `log_time` datetime NOT NULL COMMENT '日志时间',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_fp_time` (`fp_id`,`log_time`),
  KEY `idx_create_time` (`create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='巡检-原始日志样本';

CREATE TABLE IF NOT EXISTS `ai_inspect_library` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `match_type` varchar(20) NOT NULL DEFAULT 'FINGERPRINT' COMMENT '匹配维度：FINGERPRINT/LOGGER/EXCEPTION/APP',
  `match_value` varchar(500) NOT NULL COMMENT '匹配值。FINGERPRINT 存 fp_hash',
  `template` varchar(500) DEFAULT NULL COMMENT '人可读的异常模版，变量已抹成占位符',
  `pattern` varchar(1000) DEFAULT NULL COMMENT '匹配正则。入库前校验过能匹配自身样例；可人工修正',
  `business_expected` tinyint(1) NOT NULL DEFAULT '0' COMMENT '1-业务预期，正常抛出不报(突增仍报)；0-系统故障(默认)，每次出现都报',
  `sample_message` varchar(2000) DEFAULT NULL COMMENT '抽取模版时用的原始日志样例，用于校验正则与人工复核',
  `headline` varchar(500) DEFAULT NULL COMMENT '人可读的标题，列表展示用。仅冗余，不参与匹配',
  `reason` varchar(500) DEFAULT NULL COMMENT '为什么允许它发生',
  `operator` varchar(50) DEFAULT NULL COMMENT '加入人',
  `hit_count` bigint NOT NULL DEFAULT '0' COMMENT '累计命中次数',
  `last_hit_time` datetime DEFAULT NULL COMMENT '最近命中时间。长期不命中说明规则可以清理',
  `first_seen_time` datetime DEFAULT NULL COMMENT '该模版历史首现时间',
  `enabled` tinyint(1) NOT NULL DEFAULT '1' COMMENT '是否生效',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `deleted` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否删除：0-否，1-是',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_type_value` (`match_type`,`match_value`) COMMENT '同一条目不允许重复加入',
  KEY `idx_enabled` (`enabled`,`deleted`),
  KEY `idx_source` (`create_time`),
  KEY `idx_expected` (`business_expected`,`enabled`,`deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='巡检-异常模版库';

CREATE TABLE IF NOT EXISTS `ai_inspect_event` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `event_type` varchar(20) NOT NULL COMMENT '成因：NEW-不在异常库 / SURGE-在库但突增',
  `scope` varchar(20) NOT NULL DEFAULT 'SINGLE' COMMENT '范围：SINGLE-单个异常 / LOCATION-按代码位置拆分',
  `fp_id` bigint unsigned DEFAULT NULL COMMENT '来源指纹',
  `fp_hash` char(32) DEFAULT NULL COMMENT '来源指纹 hash，便于不 join 直接比对',
  `template_id` bigint unsigned DEFAULT NULL COMMENT '所属异常模版ID，事件的聚合主键',
  `headline` varchar(500) NOT NULL COMMENT '事件标题：取信息量最大的那句(异常原因 > 消息内容 > 异常类名)',
  `app_id` varchar(100) DEFAULT NULL COMMENT '服务名。跨服务合并的指纹存任一个，以 app_count 为准',
  `app_count` int NOT NULL DEFAULT '1' COMMENT '涉及服务数，>1 时页面显示「多服务」',
  `app_list` varchar(2000) DEFAULT NULL COMMENT '涉及服务列表',
  `frame_list` varchar(2000) DEFAULT NULL COMMENT '涉及的代码位置列表，逗号分隔',
  `fp_count` int NOT NULL DEFAULT '1' COMMENT '涉及指纹数',
  `exc_simple` varchar(100) DEFAULT NULL COMMENT '异常类简名',
  `exc_cause` varchar(200) DEFAULT NULL COMMENT '异常真实原因',
  `severity` varchar(4) DEFAULT NULL COMMENT '严重度 P0/P1/P2/P3，由 AI 给出',
  `first_seen_time` datetime NOT NULL COMMENT '事件开始时间',
  `last_seen_time` datetime NOT NULL COMMENT '最近一次仍在发生的时间。与开始时间之差即持续时长',
  `total_count` bigint NOT NULL DEFAULT '0' COMMENT '事件期间累计日志条数',
  `trigger_reason` varchar(500) DEFAULT NULL COMMENT '判定依据',
  `last_analyze_time` datetime DEFAULT NULL COMMENT '最近一次送 AI 分析的时间，事件维度限流用',
  `analyzed_total` bigint DEFAULT NULL COMMENT '上次分析成功时的累计次数，量级涨到它的 N 倍才重新分析',
  `analyzed_app_count` int DEFAULT NULL COMMENT '上次分析成功时涉及的服务数，扩散到新服务就重新分析',
  `handled` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否已标注。标注后停止升级重推',
  `handle_note` varchar(1000) DEFAULT NULL COMMENT '标注内容',
  `handler` varchar(50) DEFAULT NULL COMMENT '标注人',
  `handle_time` datetime DEFAULT NULL COMMENT '标注时间',
  `push_count` int NOT NULL DEFAULT '0' COMMENT '累计推送次数',
  `last_push_time` datetime DEFAULT NULL COMMENT '最近推送时间，NULL 表示从未推送',
  `last_message_id` varchar(64) DEFAULT NULL COMMENT '最近一张卡片的飞书消息ID，标注后据此把群里的卡片同步成已处理',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `deleted` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否删除：0-否，1-是',
  PRIMARY KEY (`id`),
  KEY `idx_open_fp` (`fp_id`,`handled`,`deleted`) COMMENT '查某指纹是否已有未处理事件，决定新建还是累计',
  KEY `idx_handled_seen` (`handled`,`last_seen_time`) COMMENT '列表页默认视图',
  KEY `idx_first_seen` (`first_seen_time`) COMMENT '今日新增统计',
  KEY `idx_push` (`handled`,`last_push_time`) COMMENT '重推扫描',
  KEY `idx_analyze` (`handled`,`last_analyze_time`),
  KEY `idx_open_template` (`template_id`,`handled`,`deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='巡检-异常事件';

